  // 中文全形字元的範圍：CJK 漢字、全形標點、CJK 標點。
  // 用來擋「不小心把半形逗號寫進中文題庫」這種一眼看不出來的錯。
  function isFullWidth(ch) {
    var c = ch.charCodeAt(0);
    return (c >= 0x4E00 && c <= 0x9FFF) ||    // 漢字
           (c >= 0x3000 && c <= 0x303F) ||    // 、。「」等 CJK 標點
           (c >= 0xFF00 && c <= 0xFFEF);      // ，？！；： 等全形符號
  }

  function isHan(ch) {
    var c = ch.charCodeAt(0);
    return c >= 0x4E00 && c <= 0x9FFF;
  }

  /**
   * 題庫自我檢查。這一批要防的錯跟英打那批不一樣：
   *
   *   1. **半形混進中文題庫**。`,` 和 `，` 在編輯器裡長得幾乎一樣，
   *      但學生用注音輸入法**永遠打不出半形逗號**，會卡死在那一格。
   *   2. **拼字關的字沒有注音提示**。那一關就是在練拼音，缺提示等於沒教。
   *   3. **標點關混進漢字**。那一關要練的是標點本身。
   */
  function validateLevels() {
    var problems = [];
    LEVELS_ZH_ADV.forEach(function (lv) {
      if (!lv.items || !lv.items.length) {
        problems.push(lv.id + ' 沒有任何題目');
        return;
      }
      lv.items.forEach(function (text) {
        for (var i = 0; i < text.length; i++) {
          var ch = text[i];
          if (!isFullWidth(ch)) {
            problems.push(lv.id + ' 的「' + text + '」裡的「' + ch +
                          '」是半形，注音輸入法打不出來');
            continue;
          }
          if (lv.requireZhuyinHint && isHan(ch) && !ZHUYIN_OF[ch]) {
            problems.push(lv.id + ' 的「' + ch + '」沒有注音提示，拼字關不能沒有');
          }
          if (lv.fullWidthOnly && isHan(ch) && !PUNCT_NOTE[ch] && text.length === 1) {
            problems.push(lv.id + ' 的單題「' + text + '」是漢字不是標點');
          }
        }
      });
    });
    return problems;
  }

